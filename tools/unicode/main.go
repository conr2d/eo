// Command unicode writes src/eo/unicode/tables.h, the case and white space tables of Go's unicode
// package that Eo's strings and bytes need, from the Go toolchain that runs it:
//
//	go run tools/unicode/main.go > src/eo/unicode/tables.h
package main

import (
	"fmt"
	"runtime"
	"unicode"
)

func main() {
	fmt.Println("// Copyright (c) 2026 Jeeyong \"conr2d\" Um")
	fmt.Println("// SPDX-License-Identifier: MIT")
	fmt.Println("//")
	fmt.Printf("// Generated by tools/unicode from Go %s's unicode package (Unicode %s). Do not edit.\n", runtime.Version(), unicode.Version)
	fmt.Println("#pragma once")
	fmt.Println()
	fmt.Println("#include <cstdint>")
	fmt.Println()
	fmt.Println("namespace eo::detail::unicode {")
	fmt.Println()
	fmt.Printf("inline constexpr const char* version = %q;\n\n", unicode.Version)

	// unicode.CaseRanges: Lo, Hi, and the deltas to upper, lower, and title case. A delta of
	// upper_lower marks a range whose code points alternate upper and lower case.
	fmt.Printf("inline constexpr int32_t upper_lower = %d;\n\n", unicode.UpperLower)
	fmt.Println("struct case_range {")
	fmt.Println("  uint32_t lo;")
	fmt.Println("  uint32_t hi;")
	fmt.Println("  int32_t delta[3];")
	fmt.Println("};")
	fmt.Println()
	fmt.Printf("inline constexpr case_range case_ranges[] = {\n")
	for _, cr := range unicode.CaseRanges {
		fmt.Printf("  {0x%04X, 0x%04X, {%d, %d, %d}},\n", cr.Lo, cr.Hi, cr.Delta[0], cr.Delta[1], cr.Delta[2])
	}
	fmt.Println("};")
	fmt.Println()

	// SimpleFold for every code point that it does not map to itself, in order of the code point.
	fmt.Println("struct fold_pair {")
	fmt.Println("  uint32_t from;")
	fmt.Println("  uint32_t to;")
	fmt.Println("};")
	fmt.Println()
	fmt.Println("inline constexpr fold_pair simple_fold_pairs[] = {")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := unicode.SimpleFold(r); f != r {
			fmt.Printf("  {0x%04X, 0x%04X},\n", r, f)
		}
	}
	fmt.Println("};")
	fmt.Println()

	// unicode.White_Space, as ranges of code points.
	fmt.Println("struct range {")
	fmt.Println("  uint32_t lo;")
	fmt.Println("  uint32_t hi;")
	fmt.Println("};")
	fmt.Println()
	fmt.Println("inline constexpr range white_space[] = {")
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && unicode.Is(unicode.White_Space, r)
		if in && start < 0 {
			start = r
		} else if !in && start >= 0 {
			fmt.Printf("  {0x%04X, 0x%04X},\n", start, r-1)
			start = -1
		}
	}
	fmt.Println("};")
	fmt.Println()
	fmt.Println("} // namespace eo::detail::unicode")
}
