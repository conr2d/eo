// Command unicode writes src/eo/unicode/tables.h, the case, white space, and category tables of Go's
// unicode package, from the Go toolchain that runs it:
//
//	go run tools/unicode/main.go > src/eo/unicode/tables.h
package main

import (
	"fmt"
	"runtime"
	"strings"
	"unicode"
)

func main() {
	fmt.Println("// Copyright (c) 2026 Jeeyong \"conr2d\" Um")
	fmt.Println("// SPDX-License-Identifier: MIT")
	fmt.Println("//")
	fmt.Printf("// Generated by tools/unicode from Go %s's unicode package (Unicode %s). Do not edit.\n", runtime.Version(), unicode.Version)
	fmt.Println("#pragma once")
	fmt.Println()
	fmt.Println("#include <cstdint>")
	fmt.Println()
	fmt.Println("namespace eo::detail::unicode {")
	fmt.Println()
	fmt.Printf("inline constexpr const char* version = %q;\n\n", unicode.Version)

	// unicode.CaseRanges: Lo, Hi, and the deltas to upper, lower, and title case. A delta of
	// upper_lower marks a range whose code points alternate upper and lower case.
	fmt.Printf("inline constexpr int32_t upper_lower = %d;\n\n", unicode.UpperLower)
	fmt.Println("struct case_range {")
	fmt.Println("  uint32_t lo;")
	fmt.Println("  uint32_t hi;")
	fmt.Println("  int32_t delta[3];")
	fmt.Println("};")
	fmt.Println()
	fmt.Printf("inline constexpr case_range case_ranges[] = {\n")
	for _, cr := range unicode.CaseRanges {
		fmt.Printf("  {0x%04X, 0x%04X, {%d, %d, %d}},\n", cr.Lo, cr.Hi, cr.Delta[0], cr.Delta[1], cr.Delta[2])
	}
	fmt.Println("};")
	fmt.Println()

	// SimpleFold for every code point that it does not map to itself, in order of the code point.
	fmt.Println("struct fold_pair {")
	fmt.Println("  uint32_t from;")
	fmt.Println("  uint32_t to;")
	fmt.Println("};")
	fmt.Println()
	fmt.Println("inline constexpr fold_pair simple_fold_pairs[] = {")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := unicode.SimpleFold(r); f != r {
			fmt.Printf("  {0x%04X, 0x%04X},\n", r, f)
		}
	}
	fmt.Println("};")
	fmt.Println()

	// unicode.White_Space, as ranges of code points.
	fmt.Println("struct range {")
	fmt.Println("  uint32_t lo;")
	fmt.Println("  uint32_t hi;")
	fmt.Println("};")
	fmt.Println()
	fmt.Println("inline constexpr range white_space[] = {")
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && unicode.Is(unicode.White_Space, r)
		if in && start < 0 {
			start = r
		} else if !in && start >= 0 {
			fmt.Printf("  {0x%04X, 0x%04X},\n", start, r-1)
			start = -1
		}
	}
	fmt.Println("};")
	fmt.Println()

	// The category tables, as Go's RangeTable entries: R16 and then R32, each Lo, Hi, and Stride.
	fmt.Println("struct stride_range {")
	fmt.Println("  uint32_t lo;")
	fmt.Println("  uint32_t hi;")
	fmt.Println("  uint32_t stride;")
	fmt.Println("};")
	fmt.Println()
	for _, t := range []struct {
		name  string
		table *unicode.RangeTable
	}{
		{"letter", unicode.Letter},
		{"upper", unicode.Upper},
		{"lower", unicode.Lower},
		{"title", unicode.Title},
		{"mark", unicode.Mark},
		{"number", unicode.Number},
		{"digit", unicode.Digit},
		{"punct", unicode.Punct},
		{"symbol", unicode.Symbol},
		{"zs", unicode.Zs},
	} {
		fmt.Printf("inline constexpr stride_range %s[] = {\n", t.name)
		for _, r := range t.table.R16 {
			fmt.Printf("  {0x%04X, 0x%04X, %d},\n", r.Lo, r.Hi, r.Stride)
		}
		for _, r := range t.table.R32 {
			fmt.Printf("  {0x%04X, 0x%04X, %d},\n", r.Lo, r.Hi, r.Stride)
		}
		fmt.Println("};")
		fmt.Println()
	}

	// The properties of each Latin-1 code point, which Go's predicates look up instead of searching
	// the tables: one bit per predicate.
	fmt.Println("enum : uint16_t {")
	predicates := []struct {
		name string
		is   func(rune) bool
	}{
		{"p_control", unicode.IsControl},
		{"p_letter", unicode.IsLetter},
		{"p_upper", unicode.IsUpper},
		{"p_lower", unicode.IsLower},
		{"p_title", unicode.IsTitle},
		{"p_number", unicode.IsNumber},
		{"p_punct", unicode.IsPunct},
		{"p_symbol", unicode.IsSymbol},
		{"p_graphic", unicode.IsGraphic},
		{"p_print", unicode.IsPrint},
	}
	for i, p := range predicates {
		fmt.Printf("  %s = 1 << %d,\n", p.name, i)
	}
	fmt.Println("};")
	fmt.Println()
	fmt.Println("inline constexpr uint16_t latin1_properties[256] = {")
	for r := rune(0); r <= unicode.MaxLatin1; r++ {
		var bits []string
		for _, p := range predicates {
			if p.is(r) {
				bits = append(bits, p.name)
			}
		}
		if len(bits) == 0 {
			bits = []string{"0"}
		}
		fmt.Printf("  /* 0x%02X */ %s,\n", r, strings.Join(bits, " | "))
	}
	fmt.Println("};")
	fmt.Println()
	fmt.Println("} // namespace eo::detail::unicode")
}
